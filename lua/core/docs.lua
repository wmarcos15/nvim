-- lua/core/docs.lua
--
-- :KeymapDocs (or <leader>?) opens the interactive keymap reference in your
-- browser. The page is docs/index.html; its data file docs/keymaps.js is
-- regenerated from the live config every time, so it cannot go stale:
--
--   keymaps  <- the registry in lua/core/keymaps.lua (everything this config binds)
--   themes   <- the slots in lua/core/themes.lua (the page offers the same themes)
--
-- Neovim's and the plugins' own default keys are listed by hand in
-- docs/reference.js.
local M = {}

local dir = vim.fn.stdpath("config") .. "/docs"
local port = 8765

local group_order = {
    "Find", "LSP", "Code", "Harpoon", "Git", "Run", "Debug", "Completion",
    "Editing", "Text objects", "Movement", "Windows", "Files", "Orb", "Toggles", "Themes", "General",
}

-- JSON object with its keys in a fixed order, so regenerating the file does
-- not produce a diff when nothing changed (Lua tables have no stable order).
local function object(tbl, order)
    local parts = {}
    for _, key in ipairs(order) do
        if tbl[key] ~= nil then
            table.insert(parts, vim.json.encode(key) .. ":" .. vim.json.encode(tbl[key]))
        end
    end
    return "{" .. table.concat(parts, ",") .. "}"
end

--- Write docs/keymaps.js. Returns the number of keymaps written.
function M.generate()
    -- Plugins that record their own keys when they load
    require("lazy").load({ plugins = { "telescope.nvim", "nvim-cmp", "nvim-treesitter" } })

    -- Buffer-local sets (LSP, git) are recorded when first attached; attach
    -- them to a throwaway buffer so they are always in the docs.
    local keymaps = require("core.keymaps")
    local scratch = vim.api.nvim_create_buf(false, true)
    keymaps.lsp_attach(scratch, "clangd")
    keymaps.git_attach(scratch)
    vim.api.nvim_buf_delete(scratch, { force = true })

    local rank = {}
    for i, name in ipairs(group_order) do rank[name] = i end
    local entries = {}
    for i, entry in ipairs(keymaps.registry) do
        entries[i] = vim.tbl_extend("force", entry, { order = i })
    end
    table.sort(entries, function(a, b)
        local ra, rb = rank[a.group] or 99, rank[b.group] or 99
        if ra ~= rb then return ra < rb end
        -- plugin-recorded entries load in no fixed order: sort those by key
        if a.recorded ~= b.recorded then return not a.recorded end
        if a.recorded then
            if a.keys ~= b.keys then return a.keys < b.keys end
            return table.concat(a.modes) < table.concat(b.modes)
        end
        return a.order < b.order
    end)

    local lines = {
        "// Generated by :KeymapDocs from lua/core/keymaps.lua and lua/core/themes.lua.",
        "// Do not edit by hand: change the Lua files and run :KeymapDocs again.",
        "window.NVIM_DOCS = {",
        "  groups: " .. vim.json.encode(group_order) .. ",",
        "  themes: [",
    }
    for _, palette in ipairs(require("core.themes").palettes()) do
        table.insert(lines, "    " .. object(palette, { "name", "bg", "fg", "muted", "accent", "accent2", "string", "warn" }) .. ",")
    end
    table.insert(lines, "  ],")
    table.insert(lines, "  keymaps: [")
    for _, e in ipairs(entries) do
        table.insert(lines, "    " .. object(e, { "keys", "modes", "desc", "group", "lang", "where", "tags" }) .. ",")
    end
    table.insert(lines, "  ],")
    table.insert(lines, "};")

    vim.fn.mkdir(dir, "p")
    vim.fn.writefile(lines, dir .. "/keymaps.js")
    return #entries
end

--- Regenerate, serve docs/ on localhost and open the browser.
function M.open()
    local count = M.generate()
    local url = ("http://127.0.0.1:%d/"):format(port)

    if vim.fn.executable("python3") ~= 1 then
        vim.ui.open(dir .. "/index.html") -- the page also works straight from disk
        return
    end
    if not M.job then
        -- If another Neovim already serves this port, this one exits and the
        -- URL still works (same folder).
        M.job = vim.fn.jobstart(
            { "python3", "-m", "http.server", tostring(port), "--bind", "127.0.0.1", "--directory", dir },
            { on_exit = function() M.job = nil end }
        )
    end
    vim.defer_fn(function() vim.ui.open(url) end, 400)
    vim.notify(("Keymap docs: %d keymaps at %s"):format(count, url))
end

vim.api.nvim_create_user_command("KeymapDocs", M.open, { desc = "Open the interactive keymap docs in the browser" })

return M
